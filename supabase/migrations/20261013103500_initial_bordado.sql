DO $$ BEGIN
  CREATE TYPE public.user_role AS ENUM ('user', 'admin');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE public.order_origin AS ENUM ('DTEX', 'CLIENTE');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$ BEGIN
  CREATE TYPE public.theme_mode AS ENUM ('light', 'dark');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS public.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openId" varchar(64) NOT NULL UNIQUE,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role public.user_role NOT NULL DEFAULT 'user',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  "lastSignedIn" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.embroidery_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orderDate" date NOT NULL,
  name varchar(180) NOT NULL,
  origin public.order_origin NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  "amountCents" integer NOT NULL CHECK ("amountCents" >= 0),
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.site_branding (
  id integer PRIMARY KEY,
  "logoKey" varchar(255) NOT NULL,
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.site_appearance (
  id integer PRIMARY KEY,
  "paletteId" varchar(32) NOT NULL,
  "themeMode" public.theme_mode NOT NULL DEFAULT 'light',
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS embroidery_orders_date_idx ON public.embroidery_orders ("orderDate" DESC, id DESC);

